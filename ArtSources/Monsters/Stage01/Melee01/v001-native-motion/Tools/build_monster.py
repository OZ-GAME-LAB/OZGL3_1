def bounds(objects):
    dg=bpy.context.evaluated_depsgraph_get(); pts=[]
    for o in objects:
        if o.type!='MESH': continue
        ev=o.evaluated_get(dg); me=ev.to_mesh()
        pts.extend(ev.matrix_world@v.co for v in me.vertices); ev.to_mesh_clear()
    return [min(p[i] for p in pts) for i in range(3)],[max(p[i] for p in pts) for i in range(3)]

def set_action(rig,action):
    rig.animation_data_create(); rig.animation_data.action=action
    if action.slots: rig.animation_data.action_slot=action.slots[0]
    for t in rig.animation_data.nla_tracks: t.mute=True

def target(o,p): o.rotation_euler=(Vector(p)-o.location).to_track_quat('-Z','Y').to_euler()
def camera(name,pos,look,ortho=3.4):
    d=bpy.data.cameras.new(name);o=bpy.data.objects.new(name,d);bpy.context.collection.objects.link(o)
    o.location=pos;target(o,look);d.type='ORTHO';d.ortho_scale=ortho;return o
def flatmat(name,c):
    m=bpy.data.materials.new(name);m.diffuse_color=(*c,1);m.use_nodes=True
    p=m.node_tree.nodes.get('Principled BSDF');p.inputs['Base Color'].default_value=(*c,1);p.inputs['Roughness'].default_value=0.85;return m

